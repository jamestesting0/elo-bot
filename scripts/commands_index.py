"""Generate docs/commands.md: every slash command, component, modal, listener and Task mapped to the code that handles it.

    python scripts/commands_index.py          # rewrite docs/commands.md
    python scripts/commands_index.py --check  # exit 1 if docs/commands.md is stale
"""
import functools
import inspect
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUTPUT = REPO / "docs" / "commands.md"
DUMMY_ENV = {
    "BOT_MAIN_TOKEN": "dummy-main-token",
    "BOT_BETA_TOKEN": "dummy-beta-token",
    "COC_API_EMAIL": "dummy@example.invalid",
    "COC_API_PASSWORD": "dummy-coc-password",
    "MONGO_DB_URL": "mongodb://dummy.invalid:27017",
}


def location(callback) -> str:
    callback = getattr(callback, "callback", callback)
    while isinstance(callback, functools.partial):
        callback = callback.func
    callback = inspect.unwrap(getattr(callback, "__func__", callback))
    path = Path(inspect.getsourcefile(callback)).resolve().relative_to(REPO)
    return f"`{path}` `{callback.__qualname__}`"


def section(title: str, rows: list[tuple[str, str]]) -> list[str]:
    return [f"## {title}", "", *(f"- {key} -> {where}" for key, where in sorted(rows)), ""]


def render() -> str:
    for key, value in DUMMY_ENV.items():
        os.environ.setdefault(key, value)
    sys.path.insert(0, str(REPO))
    import interactions as ipy

    from elo_bot.app import backups, root_callbacks
    from elo_bot.app.extensions import EXTENSIONS

    bot = ipy.Client()
    for name in EXTENSIONS:
        bot.load_extension(name)
    root_callbacks.register(bot)
    commands = {(f"`/{cmd.resolved_name}`", location(cmd.callback))
                for entries in bot.interactions_by_scope.values() for cmd in entries.values()
                if isinstance(cmd, ipy.SlashCommand) and cmd.callback}
    context_menus = {(f"`{cmd.resolved_name}`", location(cmd.callback))
                     for entries in bot.interactions_by_scope.values() for cmd in entries.values()
                     if not isinstance(cmd, ipy.SlashCommand) and cmd.callback}
    autocompletes = {(f"`/{cmd.resolved_name}` option `{option}`", location(callback))
                     for entries in bot.interactions_by_scope.values() for cmd in entries.values()
                     for option, callback in (getattr(cmd, "autocomplete_callbacks", None) or {}).items()}
    autocompletes |= {(f"any command, option `{option}`", location(callback))
                      for option, callback in getattr(bot, "_global_autocompletes", {}).items()}

    def callbacks(literal: dict, regex: dict) -> set:
        return {(f"`{key}`", location(cmd.callback)) for key, cmd in literal.items()} | \
            {(f"regex `{key.pattern}`", location(cmd.callback)) for key, cmd in regex.items()}

    listeners = {(f"`{event}`", location(listener.callback))
                 for event, items in bot.listeners.items() for listener in items}
    tasks = {(f"{type(value.trigger).__name__}", location(value.callback))
             for ext in bot.ext.values() for _, value in inspect.getmembers(type(ext)) if isinstance(value, ipy.Task)}
    tasks |= {(f"{type(value.trigger).__name__}", location(value.callback))
              for module in (*root_callbacks.ROOT_MODULES, backups) for value in vars(module).values()
              if isinstance(value, ipy.Task)}
    lines = ["# Commands index", "",
             "Generated by `python scripts/commands_index.py`; do not edit by hand.", ""]
    lines += section("Slash commands", list(commands))
    if context_menus:
        lines += section("Context menus", list(context_menus))
    lines += section("Autocomplete", list(autocompletes))
    lines += section("Components (custom ID)", list(callbacks(bot._component_callbacks, bot._regex_component_callbacks)))
    lines += section("Modals (custom ID)", list(callbacks(bot._modal_callbacks, bot._regex_modal_callbacks)))
    lines += section("Listeners (event)", list(listeners))
    lines += section("Tasks (trigger)", list(tasks))
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if argv == ["--check"]:
        if OUTPUT.read_text() != text:
            print("docs/commands.md is stale; run `python scripts/commands_index.py`")
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
